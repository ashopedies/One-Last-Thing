function A.Translate(text)
    if not A.IsGerman() or type(text)~="string" then return text end
    if de[text] then return de[text] end
    if text:find("\n",1,true) then
        local result=text:gsub("[^\n]+",function(line) return A.Translate(line) end);return result
    end
    local left,right=text:match("^(.-) | (.+)$")
    if left then return A.Translate((left:gsub("%s+$",""))).." | "..A.Translate((right:gsub("^%s+",""))) end
    for _,rule in ipairs(patterns) do
        if text:match(rule[1]) then local result=text:gsub(rule[1],rule[2]);return result end
    end
    -- Settings slider labels have translated names plus numeric/percentage values.
    local key,value=text:match("^(.-): (.+)$")
    if key and de[key] then return de[key]..": "..value end
    return text
end
function A.SetText(frame,text,...) return frame:SetText(A.Translate(text),...) end
