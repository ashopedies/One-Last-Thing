    if not name then return end
    if GetProfessions and GetProfessionInfo then
        for _,index in pairs({GetProfessions()}) do
            local ok,n,_,_,_,_,_,id=pcall(GetProfessionInfo,index)
            if ok and n==name then return id end
        end
    end
    local ids={["First Aid"]=129,Cooking=185,Fishing=356,Alchemy=171,Blacksmithing=164,Enchanting=333,Engineering=202,
        Herbalism=182,Leatherworking=165,Mining=186,Skinning=393,Tailoring=197}
    for english,id in pairs(ids) do if name==english or name==de[english] then return id end end
end
